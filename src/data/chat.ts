export function getCoachReply(input: string): string {
  const message = input.trim().toLowerCase();

  if (/كمي|نسبة|معادلة|رياضيات|حساب/.test(message)) {
    return 'تمام. سؤال كمي:\n\nإذا كان ٣٠٪ من عدد يساوي ١٨، فما العدد؟\n\nأ) ٤٨\nب) ٥٤\nج) ٦٠\nد) ٧٢\n\nاكتب الحرف أو الإجابة، وبعدها أشرح لك الطريقة الأسرع بدون حفظ طويل.';
  }

  if (/تناظر|لفظي|كلمة|معنى|مفردات/.test(message)) {
    return 'التناظر اللفظي يقيس العلاقة بين الكلمتين، وليس معنى كل كلمة منفردة. مثال:\n\nقلم : كتابة :: فرشاة : ؟\n\nالعلاقة هي «أداة تُستخدم في فعل»، لذلك الإجابة: رسم.\n\nالقاعدة: حوّل الزوج الأول إلى جملة قصيرة، ثم طبّق نفس الجملة على الزوج الثاني.';
  }

  if (/خطة|١٤|14|مذاكرة|جدول/.test(message)) {
    return 'هذه بداية خطة ١٤ يومًا:\n\nالأيام ١–٣: أساسيات النسب والكسور والمتوسطات.\nالأيام ٤–٦: الجبر والهندسة والمسائل اللفظية.\nالأيام ٧–٩: التناظر وإكمال الجمل والمفردة الشاذة.\nالأيام ١٠–١٢: تدريب مختلط مع دفتر أخطاء.\nالأيام ١٣–١٤: محاكاتان بزمن كامل ومراجعة الأخطاء فقط.\n\nكل يوم: ٤٥ دقيقة تدريب + ١٥ دقيقة مراجعة أخطاء.';
  }

  if (/محاكاة|اختبار|اختبرني|سريع/.test(message)) {
    return 'نبدأ بمحاكاة قصيرة من ٣ أسئلة. سأرسل سؤالًا واحدًا كل مرة، وسأسجل نوع الخطأ والوقت التقريبي:\n\nالسؤال الأول: متوسط ثلاثة أعداد هو ١٢، ومجموع عددين منها ١٩. ما العدد الثالث؟\n\nأ) ١٥\nب) ١٧\nج) ١٩\nد) ٢١';
  }

  if (/صورة|ارفع|رفع/.test(message)) {
    return 'ارفع صورة السؤال من زر الإضافة بجانب خانة الكتابة. عند ربط خدمة الصور الآمنة، سأقرأ السؤال وأشرح الحل خطوة خطوة، مع التنبيه إذا كانت الصورة غير واضحة.';
  }

  return 'فهمت عليك. أنا مدربك في القدرات، وأقدر أشرح الفكرة ثم أختبرك عليها بدل إعطائك الإجابة فقط. اكتب السؤال كما هو أو اختر أحد المسارات السريعة تحت المحادثة.';
}
